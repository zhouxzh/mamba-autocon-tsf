class Dataset_Array(Dataset):
    """Chronological numeric-array dataset for optional Solar/PEMS inputs.

    This adapter intentionally does not reinterpret an array as CSV.  It
    accepts a dense numeric time-by-channel matrix, or a timestamp-first CSV
    numeric matrix, and uses the same
    train-only standardization and ratio-based split convention as
    :class:`Dataset_Custom`.  Timestamp features are synthetic, regular
    calendar marks anchored at 2000-01-01; the source arrays carry no observed
    timestamps, so users must set ``freq`` to the documented sampling interval.
    """

    def __init__(self, root_path, flag='train', size=None,
                 features='S', data_path='data.npz', target='OT', scale=True,
                 timeenc=0, freq='h', seasonal_patterns=None, train_ratio=0.6,
                 data_format='auto', data_key='data', data_feature_index=0,
                 target_index=-1, data_interval_minutes=None,
                 data_start_timestamp='2000-01-01'):
        if size is None:
            self.seq_len = 24 * 4 * 4
            self.label_len = 24 * 4
            self.pred_len = 24 * 4
        else:
            self.seq_len = int(size[0])
            self.label_len = int(size[1])
            self.pred_len = int(size[2])
        if min(self.seq_len, self.label_len, self.pred_len) < 0 or self.seq_len <= 0:
            raise ValueError('array dataset sequence lengths must be positive except label_len')
        if flag not in {'train', 'test', 'val'}:
            raise ValueError("flag must be one of 'train', 'val', 'test'")
        if features not in {'S', 'M', 'MS'}:
            raise ValueError("features must be one of 'S', 'M', 'MS'")
        try:
            train_ratio = float(train_ratio)
        except (TypeError, ValueError) as exc:
            raise ValueError('train_ratio must be a finite number in (0, 0.8)') from exc
        if not np.isfinite(train_ratio) or not 0.0 < train_ratio < 0.8:
            raise ValueError('train_ratio must be a finite number in (0, 0.8)')

        self.set_type = {'train': 0, 'val': 1, 'test': 2}[flag]
        self.features = features
        self.target = target
        self.scale = bool(scale)
        self.timeenc = int(timeenc)
        self.freq = str(freq).strip().lower()
        self.train_ratio = train_ratio
        self.root_path = root_path
        self.data_path = data_path
        self.data_format = data_format
        self.data_key = data_key
        self.data_feature_index = data_feature_index
        self.target_index = target_index
        if isinstance(data_interval_minutes, (bool, np.bool_)):
            raise ValueError('data_interval_minutes must be a positive integer')
        try:
            data_interval_minutes = int(data_interval_minutes) if data_interval_minutes is not None else None
        except (TypeError, ValueError) as exc:
            raise ValueError('data_interval_minutes must be a positive integer') from exc
        if data_interval_minutes is not None and data_interval_minutes <= 0:
            raise ValueError('data_interval_minutes must be a positive integer')
        self.data_interval_minutes = data_interval_minutes
        try:
            self.data_start_timestamp = pd.Timestamp(data_start_timestamp)
        except (TypeError, ValueError) as exc:
            raise ValueError('data_start_timestamp must be a valid timestamp') from exc
        if pd.isna(self.data_start_timestamp):
            raise ValueError('data_start_timestamp must be a valid timestamp')
        self.__read_data__()

    def _resolve_target_index(self, channel_count):
        if self.features == 'M':
            return None
        if isinstance(self.target_index, (bool, np.bool_)):
            raise ValueError('target_index must be an integer for array datasets')
        try:
            index = int(self.target_index)
        except (TypeError, ValueError) as exc:
            raise ValueError('target_index must be an integer for array datasets') from exc
        if index < 0:
            index += int(channel_count)
        if index < 0 or index >= int(channel_count):
            raise ValueError(
                'target_index={} is outside {} array channels'.format(
                    self.target_index, channel_count
                )
            )
        return index

    def _synthetic_marks(self, total_rows):
        if self.freq == 't':
            if self.data_interval_minutes is None:
                raise ValueError(
                    "freq='t' requires a positive data_interval_minutes for numeric arrays"
                )
            pandas_freq = '{}min'.format(self.data_interval_minutes)
        else:
            pandas_freq = _ARRAY_PANDAS_FREQUENCIES.get(self.freq)
        if pandas_freq is None:
            raise ValueError(
                "numeric array datasets require freq in {}; got {!r}".format(
                    sorted(_ARRAY_PANDAS_FREQUENCIES), self.freq
                )
            )
        dates = pd.date_range(
            self.data_start_timestamp, periods=int(total_rows), freq=pandas_freq
        )
        if self.timeenc == 0:
            return np.column_stack((
                dates.month.to_numpy(),
                dates.day.to_numpy(),
                dates.dayofweek.to_numpy(),
                dates.hour.to_numpy(),
                (dates.minute.to_numpy() // 15),
            )).astype(np.int64, copy=False)
        if self.timeenc == 1:
            return time_features(dates, freq=self.freq).transpose(1, 0).astype(
                np.float32, copy=False
            )
        raise ValueError('timeenc must be 0 or 1 for array datasets')

    def __read_data__(self):
        path = os.path.join(self.root_path, self.data_path)
        raw = load_numeric_array_file(
            path,
            data_format=self.data_format,
            data_key=self.data_key,
            data_feature_index=self.data_feature_index,
        )
        total_rows, channel_count = raw.shape
        target_index = self._resolve_target_index(channel_count)
        if self.features == 'M':
            values = raw
        elif self.features == 'S':
            values = raw[:, [target_index]]
        else:
            # Match Dataset_Custom's MS contract: retain every input channel,
            # but move the requested target to the final column so the
            # trainer's ``f_dim=-1`` slice selects it deterministically.
            channel_order = [
                index for index in range(channel_count) if index != target_index
            ] + [target_index]
            values = raw[:, channel_order]

        num_train = int(total_rows * self.train_ratio)
        num_test = int(total_rows * 0.2)
        num_vali = total_rows - num_train - num_test
        if min(num_train, num_vali, num_test) <= 0:
            raise ValueError(
                'array dataset is too short for train/validation/test split: '
                'rows={}, train_ratio={}'.format(total_rows, self.train_ratio)
            )
        border1s = [0, num_train - self.seq_len, total_rows - num_test - self.seq_len]
        border2s = [num_train, num_train + num_vali, total_rows]
        border1, border2 = border1s[self.set_type], border2s[self.set_type]
        if border1 < 0 or border2 - border1 < self.seq_len + self.pred_len:
            raise ValueError(
                'array dataset split {!r} is too short for seq_len={} and pred_len={}; '
                'rows={}, train_rows={}, validation_rows={}, test_rows={}'.format(
                    ('train', 'val', 'test')[self.set_type], self.seq_len,
                    self.pred_len, total_rows, num_train, num_vali, num_test
                )
            )

        self.scaler = StandardScaler()
        if self.scale:
            self.scaler.fit(values[:num_train])
            data = self.scaler.transform(values)
        else:
            data = values.astype(np.float32, copy=False)
        marks = self._synthetic_marks(total_rows)

        self.data_x = data[border1:border2]
        self.data_y = data[border1:border2]
        self.data_stamp = marks[border1:border2]
        self.full_data_x = data
        self.full_data_stamp = marks
        self.channel_count = int(channel_count)
        self.selected_target_index = target_index

    def __getitem__(self, index):
        s_begin = index
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len
        return (
            index,
            self.data_x[s_begin:s_end],
            self.data_y[r_begin:r_end],
            self.data_stamp[s_begin:s_end],
            self.data_stamp[r_begin:r_end],
        )

    def __len__(self):
        return len(self.data_x) - self.seq_len - self.pred_len + 1

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)
