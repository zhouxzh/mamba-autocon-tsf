_ARRAY_DATA_FORMATS = frozenset({'auto', 'npz', 'txt', 'csv_numeric'})
_ARRAY_PANDAS_FREQUENCIES = {
    'h': 'h',
    'd': 'D',
    'w': 'W',
    'm': 'MS',
    's': 's',
}


def _normalise_array_data_format(data_format, path):
    """Resolve the explicitly supported numeric-array file format."""

    value = str(data_format or 'auto').strip().lower()
    if value not in _ARRAY_DATA_FORMATS:
        raise ValueError(
            "data_format must be one of 'npz', 'txt', or 'auto' (got {!r})".format(
                data_format
            )
        )
    if value == 'auto':
        suffix = os.path.splitext(os.fspath(path))[1].lower()
        value = {'.npz': 'npz', '.txt': 'txt', '.csv': 'csv_numeric'}.get(suffix)
        if value is None:
            raise ValueError(
                "cannot infer numeric dataset format from {!r}; pass "
                "data_format='npz', 'txt', or 'csv_numeric'".format(os.fspath(path))
            )
    return value


def load_numeric_array_file(path, data_format='auto', data_key='data',
                            data_feature_index=0):
    """Load a numeric Solar/PEMS-style array as ``[time, channels]``.

    Supported formats are deliberately narrow and auditable:

    * ``npz``: an archive containing a numeric ``data`` array (or the
      explicitly supplied ``data_key``), shaped ``[T, C]`` or ``[T, C, F]``.
      Three-dimensional arrays require an integer feature index ``F``.
    * ``txt``: header-free, whitespace-delimited numeric rows shaped ``[T, C]``.
    * ``csv_numeric``: a header row whose first column is a timestamp or row
      label and whose remaining columns are finite numeric series.

    No timestamp or metadata columns are inferred.  A regular calendar is
    generated by :class:`Dataset_Array` solely for the existing time-feature
    embedding interface.
    """

    path = os.path.abspath(os.fspath(path))
    if not os.path.isfile(path):
        raise FileNotFoundError(
            "numeric array dataset file is missing: {}".format(path)
        )
    resolved_format = _normalise_array_data_format(data_format, path)
    if resolved_format == 'npz':
        key = str(data_key or 'data').strip()
        if not key:
            raise ValueError("data_key must be non-empty for npz datasets")
        try:
            with np.load(path, allow_pickle=False) as archive:
                if key not in archive.files:
                    raise ValueError(
                        "npz dataset {!r} does not contain data_key {!r}; "
                        "available keys: {}".format(path, key, sorted(archive.files))
                    )
                raw = np.asarray(archive[key])
        except ValueError:
            raise
        except (OSError, EOFError, TypeError) as exc:
            raise ValueError(
                "cannot read npz numeric dataset {!r}: {}".format(path, exc)
            ) from exc
    elif resolved_format == 'txt':
        try:
            # ``ndmin=2`` keeps a one-row file from silently becoming 1-D.
            raw = np.loadtxt(path, dtype=np.float64, ndmin=2)
        except (OSError, ValueError) as whitespace_exc:
            # The canonical Solar file is distributed by some mirrors as a
            # comma-delimited text matrix.  Accept that representation too,
            # while retaining the no-header/finite-numeric contract.
            try:
                raw = np.loadtxt(path, dtype=np.float64, delimiter=',', ndmin=2)
            except (OSError, ValueError) as comma_exc:
                raise ValueError(
                    "txt numeric dataset {!r} must be header-free and "
                    "whitespace- or comma-delimited: {}".format(
                        path, comma_exc
                    )
                ) from whitespace_exc
    else:
        try:
            frame = pd.read_csv(path)
        except (OSError, ValueError, pd.errors.ParserError) as exc:
            raise ValueError(
                "cannot read csv_numeric dataset {!r}: {}".format(path, exc)
            ) from exc
        if frame.shape[1] < 2:
            raise ValueError(
                "csv_numeric dataset must contain one timestamp column and at least one numeric channel"
            )
        raw = frame.iloc[:, 1:].to_numpy(dtype=np.float64, copy=True)

    if raw.ndim == 3:
        if isinstance(data_feature_index, (bool, np.bool_)):
            raise ValueError('data_feature_index must be an integer')
        try:
            feature_index = int(data_feature_index)
        except (TypeError, ValueError) as exc:
            raise ValueError('data_feature_index must be an integer') from exc
        if feature_index < 0:
            feature_index += int(raw.shape[2])
        if feature_index < 0 or feature_index >= int(raw.shape[2]):
            raise ValueError(
                'data_feature_index={} is outside npz feature axis of size {}'.format(
                    data_feature_index, raw.shape[2]
                )
            )
        raw = raw[:, :, feature_index]
    elif raw.ndim != 2:
        raise ValueError(
            "numeric dataset must have shape [time, channels] or [time, "
            "channels, features]; got {}".format(tuple(raw.shape))
        )

    if raw.shape[0] < 1 or raw.shape[1] < 1:
        raise ValueError(
            "numeric dataset must contain at least one time row and one channel; "
            "got {}".format(tuple(raw.shape))
        )
    try:
        values = np.asarray(raw, dtype=np.float32)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            "numeric dataset values cannot be converted to float32"
        ) from exc
    if not np.all(np.isfinite(values)):
        raise ValueError(
            "numeric dataset contains NaN or infinite values: {}".format(path)
        )
    return values


def inspect_numeric_array_file(path, data_format='auto', data_key='data',
                               data_feature_index=0):
    """Return a small, JSON-friendly schema summary for a numeric dataset."""

    values = load_numeric_array_file(
        path,
        data_format=data_format,
        data_key=data_key,
        data_feature_index=data_feature_index,
    )
    return {
        'format': _normalise_array_data_format(data_format, path),
        'shape': [int(item) for item in values.shape],
        'dtype': str(values.dtype),
    }


class Dataset_ETT_hour(Dataset):
    def __init__(self, root_path, flag='train', size=None,
                 features='S', data_path='ETTh1.csv',
                 target='OT', scale=True, timeenc=0, freq='h', seasonal_patterns=None, train_ratio=0.6):
        # size [seq_len, label_len, pred_len]
        # info
        if size == None:
            self.seq_len = 24 * 4 * 4
            self.label_len = 24 * 4
            self.pred_len = 24 * 4
        else:
            self.seq_len = size[0]
            self.label_len = size[1]
            self.pred_len = size[2]
        # init
        assert flag in ['train', 'test', 'val']
        type_map = {'train': 0, 'val': 1, 'test': 2}
        self.set_type = type_map[flag]

        self.features = features
        self.target = target
        self.scale = scale
        self.timeenc = timeenc
        self.freq = freq

        self.root_path = root_path
        self.data_path = data_path
        self.__read_data__()

    def __read_data__(self):
        self.scaler = StandardScaler()
        df_raw = pd.read_csv(os.path.join(self.root_path,
                                          self.data_path))

        border1s = [0, 12 * 30 * 24 - self.seq_len, 12 * 30 * 24 + 4 * 30 * 24 - self.seq_len]
        border2s = [12 * 30 * 24, 12 * 30 * 24 + 4 * 30 * 24, 12 * 30 * 24 + 8 * 30 * 24]
        border1 = border1s[self.set_type]
        border2 = border2s[self.set_type]

        if self.features == 'M' or self.features == 'MS':
            cols_data = df_raw.columns[1:]
            df_data = df_raw[cols_data]
        elif self.features == 'S':
            df_data = df_raw[[self.target]]

        if self.scale:
            train_data = df_data[border1s[0]:border2s[0]]
            self.scaler.fit(train_data.values)
            data = self.scaler.transform(df_data.values)
        else:
            data = df_data.values

        df_stamp = df_raw[['date']][border1:border2]
        df_stamp['date'] = pd.to_datetime(df_stamp.date)
        if self.timeenc == 0:
            df_stamp['month'] = df_stamp.date.apply(lambda row: row.month, 1)
            df_stamp['day'] = df_stamp.date.apply(lambda row: row.day, 1)
            df_stamp['weekday'] = df_stamp.date.apply(lambda row: row.weekday(), 1)
            df_stamp['hour'] = df_stamp.date.apply(lambda row: row.hour, 1)
            data_stamp = df_stamp.drop(columns=['date']).values
        elif self.timeenc == 1:
            data_stamp = time_features(pd.to_datetime(df_stamp['date'].values), freq=self.freq)
            data_stamp = data_stamp.transpose(1, 0)

        self.data_x = data[border1:border2]
        self.data_y = data[border1:border2]
        self.data_stamp = data_stamp

        self.month_label = df_stamp['month'] = df_stamp.date.apply(lambda row: row.month, 1).values
    def __getitem__(self, index):
        s_begin = index
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len

        seq_x = self.data_x[s_begin:s_end]
        seq_y = self.data_y[r_begin:r_end]
        seq_x_mark = self.data_stamp[s_begin:s_end]
        seq_y_mark = self.data_stamp[r_begin:r_end]

        # index = self.month_label[s_begin:s_end]

        return index, seq_x, seq_y, seq_x_mark, seq_y_mark

    def __len__(self):
        return len(self.data_x) - self.seq_len - self.pred_len + 1

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)


